-- Usuarios (auth_subject = "google:<sub>" o "dev:<email>" en desarrollo)
CREATE TABLE app_user (
    id              UUID PRIMARY KEY,
    auth_subject    VARCHAR(255) NOT NULL UNIQUE,
    email           VARCHAR(320) NOT NULL,
    name            VARCHAR(200),
    avatar_url      VARCHAR(1000),
    plan            VARCHAR(20)  NOT NULL DEFAULT 'FREE',
    created_at      TIMESTAMPTZ  NOT NULL,
    last_login_at   TIMESTAMPTZ  NOT NULL
);

-- "Mi garaje": vehículos de cada usuario
CREATE TABLE vehicle (
    id          UUID PRIMARY KEY,
    user_id     UUID         NOT NULL REFERENCES app_user (id) ON DELETE CASCADE,
    brand_id    VARCHAR(60),
    brand       VARCHAR(60)  NOT NULL,
    model_id    VARCHAR(80),
    model       VARCHAR(80)  NOT NULL,
    model_year  INTEGER      NOT NULL,
    engine      VARCHAR(100),
    fuel        VARCHAR(30),
    power_cv    INTEGER,
    created_at  TIMESTAMPTZ  NOT NULL
);
CREATE INDEX idx_vehicle_user ON vehicle (user_id, created_at DESC);

-- Conversaciones con la IA (cada una ligada a un vehículo)
CREATE TABLE conversation (
    id          UUID PRIMARY KEY,
    user_id     UUID         NOT NULL REFERENCES app_user (id) ON DELETE CASCADE,
    vehicle_id  UUID         NOT NULL REFERENCES vehicle (id) ON DELETE CASCADE,
    title       VARCHAR(120) NOT NULL,
    created_at  TIMESTAMPTZ  NOT NULL,
    updated_at  TIMESTAMPTZ  NOT NULL
);
CREATE INDEX idx_conversation_user ON conversation (user_id, updated_at DESC);

CREATE TABLE message (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    conversation_id  UUID        NOT NULL REFERENCES conversation (id) ON DELETE CASCADE,
    role             VARCHAR(20) NOT NULL,
    content          TEXT        NOT NULL,
    created_at       TIMESTAMPTZ NOT NULL
);
CREATE INDEX idx_message_conversation ON message (conversation_id, id);

-- Contadores de uso diario (mensajes por usuario / invitado / IP)
CREATE TABLE usage_counter (
    subject  VARCHAR(120) NOT NULL,
    day      DATE         NOT NULL,
    count    INTEGER      NOT NULL,
    PRIMARY KEY (subject, day)
);

-- Motorizaciones sugeridas por la IA, cacheadas por marca/modelo/año
CREATE TABLE engine_cache (
    brand_id      VARCHAR(60) NOT NULL,
    model_id      VARCHAR(80) NOT NULL,
    model_year    INTEGER     NOT NULL,
    engines_json  TEXT        NOT NULL,
    created_at    TIMESTAMPTZ NOT NULL,
    PRIMARY KEY (brand_id, model_id, model_year)
);
